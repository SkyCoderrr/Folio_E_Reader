/**
 * JSON Merge Patch (RFC 7396) over T: absent = unchanged, null = reset to default (delete),
 * object = merge recursively, array = replace wholesale.
 */
export type MergePatch<T> = {
  [K in keyof T]?: NonNullable<T[K]> extends readonly unknown[]
    ? NonNullable<T[K]> | null
    : NonNullable<T[K]> extends object
      ? MergePatch<NonNullable<T[K]>> | null
      : T[K] | null;
};
export type SettingsPatch = MergePatch<Omit<Settings, 'version'>>;

