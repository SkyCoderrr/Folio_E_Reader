/**
 * E_Reader IPC contract: TypeScript types.
 *
 * Contract version 0.9.0 (see contract/README.md). Owner: Dany_PM.
 * Agents never edit this file; propose changes in .agent-logs/conversation.md.
 *
 * Rules (full text in README.md and rust-types.md):
 * - Command names are snake_case. Event names are `domain://name`.
 * - JSON keys are camelCase. Rust uses #[serde(rename_all = "camelCase")].
 * - `T | null` = the key is ALWAYS present and may be null (Rust Option<T>, serialized as null).
 * - `key?: T` (optional key) is used ONLY in patch/override types and in AppError.details.
 * - Timestamps are integer Unix milliseconds, UTC (UnixMs). Ids are strings.
 * - Absolute paths are loaded in the webview only via convertFileSrc(path) (asset protocol).
 *
 * This file is pure types. The only runtime values are `as const` arrays that define string unions.
 * The matching Rust definitions are in contract/rust-types.md (one-to-one, same names).
 */

export const CONTRACT_VERSION = '0.9.0' as const;

// ───────────────────────────── Primitives ─────────────────────────────

/** Integer Unix epoch milliseconds, UTC. Rust: i64. */
// All integer IPC values must be safe integers (unsigned <= 9007199254740991;
// UnixMs within +/-9007199254740991); narrower field ranges still apply.
// Locator charOffset/globalCharOffset, TxtSection startChar/chars and totalChars
// count UTF-16 code units. Display-string bounds count Unicode scalars.
export type UnixMs = number;
/** Book id: the first 32 lowercase hex chars of BLAKE3(file bytes). Pattern ^[0-9a-f]{32}$. */
export type BookId = string;
/** Bookmark id: decimal string of the SQLite rowid, e.g. "42". */
export type BookmarkId = string;
/** Import job id, generated by the UI. Pattern ^[A-Za-z0-9_-]{1,64}$. */
export type JobId = string;
/** Absolute Windows path (drive or UNC). In the webview, load it only via convertFileSrc(path). */
export type AbsPath = string;
/** Colour: #RRGGBB or #RRGGBBAA (hex digits of either case). */
export type ColorHex = string;
/**
 * Key chord. Grammar (see settings.md › Chords): optional modifiers in the fixed order
 * `Ctrl+`, `Alt+`, `Shift+`, then exactly one key token = KeyboardEvent.code, except that
 * `KeyA`…`KeyZ` are written `A`…`Z` and `Digit0`…`Digit9` are written `0`…`9`.
 * Examples: "Ctrl+Alt+B", "PageDown", "Shift+Space", "Ctrl+Equal", "BracketRight", "F11".
 */
export type Chord = string;
/** "builtin.dark" | "builtin.sepia" | "builtin.light" | "builtin.night" | "custom.<1-64 of [A-Za-z0-9_-]>" */
export type PresetId = string;
/** Any JSON value. */
export type JsonValue = null | boolean | number | string | JsonValue[] | { [key: string]: JsonValue };
/** Args object of a command that takes no arguments: always `{}`. */
export type EmptyArgs = Record<string, never>;

